using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using RedKey.Domain.Entities.Accounting;
using RedKey.Domain.Enums;

namespace RedKey.Persistence.Configurations.Accounting;

internal sealed class AccountConfiguration : IEntityTypeConfiguration<Account>
{
    public void Configure(EntityTypeBuilder<Account> builder)
    {
        builder.ToTable(TableNames.Accounts);
        builder.HasKey(a => a.Id);
        builder.Property(a => a.Id).ValueGeneratedNever();

        builder.Property(a => a.Code).HasMaxLength(10).IsUnicode(false).IsRequired();
        builder.HasIndex(a => a.Code).IsUnique();
        builder.Property(a => a.NameAr).HasMaxLength(100).IsRequired();
        builder.Property(a => a.NameEn).HasMaxLength(100).IsRequired();

        // The whole chart in one go (the later phases use the rest: sales, rents, broker commissions).
        builder.HasData(
            Seed(1, SystemAccounts.Cash, "الخزنة النقدية", "Cash box", AccountType.Asset, isCash: true),
            Seed(2, SystemAccounts.Bank, "البنك", "Bank", AccountType.Asset, isCash: true),
            Seed(3, SystemAccounts.CustomerReceivables, "مستحقات على العملاء", "Customer receivables", AccountType.Asset),
            Seed(4, SystemAccounts.BrokerCommissionsPayable, "عمولات وسطاء مستحقة", "Broker commissions payable", AccountType.Liability),
            Seed(5, SystemAccounts.ViewingFeeRevenue, "إيراد رسوم المعاينة", "Viewing fee revenue", AccountType.Revenue),
            Seed(6, SystemAccounts.SaleCommissionRevenue, "إيراد عمولة بيع", "Sale commission revenue", AccountType.Revenue),
            Seed(7, SystemAccounts.RentCommissionRevenue, "إيراد عمولة إيجار", "Rent commission revenue", AccountType.Revenue),
            Seed(8, SystemAccounts.BrokerCommissionExpense, "مصروف عمولات الوسطاء", "Broker commission expense", AccountType.Expense));
    }

    private static object Seed(int id, string code, string ar, string en, AccountType type, bool isCash = false) => new
    {
        Id = id,
        Code = code,
        NameAr = ar,
        NameEn = en,
        Type = type,
        IsCash = isCash,
        IsSystem = true,
        IsActive = true
    };
}

internal sealed class JournalEntryConfiguration : IEntityTypeConfiguration<JournalEntry>
{
    public void Configure(EntityTypeBuilder<JournalEntry> builder)
    {
        builder.ToTable(TableNames.JournalEntries);
        builder.HasKey(e => e.Id);
        builder.Property(e => e.Id).ValueGeneratedNever();

        // JE-100001, JE-100002... generated by SQL Server on insert.
        builder.Property(e => e.Number)
            .HasMaxLength(20)
            .IsUnicode(false)
            .HasDefaultValueSql($"CONCAT('JE-', NEXT VALUE FOR {TableNames.JournalNumberSequence})")
            .ValueGeneratedOnAdd();
        builder.HasIndex(e => e.Number).IsUnique();

        builder.Property(e => e.DescriptionAr).HasMaxLength(300).IsRequired();
        builder.Property(e => e.DescriptionEn).HasMaxLength(300).IsRequired();

        // One active posting per business record: clicking "completed" twice cannot post twice.
        builder.HasIndex(e => new { e.SourceType, e.SourceId })
            .IsUnique()
            .HasFilter("[ReversalOfId] IS NULL AND [IsReversed] = 0");
        builder.HasIndex(e => e.UnitId);
        builder.HasIndex(e => e.EntryDateUtc);

        builder.HasMany(e => e.Lines).WithOne().HasForeignKey(l => l.EntryId).OnDelete(DeleteBehavior.Cascade);
        builder.Navigation(e => e.Lines).UsePropertyAccessMode(PropertyAccessMode.Field);
    }
}

internal sealed class JournalLineConfiguration : IEntityTypeConfiguration<JournalLine>
{
    public void Configure(EntityTypeBuilder<JournalLine> builder)
    {
        builder.ToTable(TableNames.JournalLines, t =>
        {
            t.HasCheckConstraint("CK_RK_JournalLines_Amounts", "[Debit] >= 0 AND [Credit] >= 0");
            t.HasCheckConstraint("CK_RK_JournalLines_OneSide", "([Debit] > 0 AND [Credit] = 0) OR ([Credit] > 0 AND [Debit] = 0)");
        });
        builder.HasKey(l => l.Id);

        builder.Property(l => l.Debit).HasPrecision(18, 2);
        builder.Property(l => l.Credit).HasPrecision(18, 2);
        builder.Property(l => l.Memo).HasMaxLength(200);

        // Balances / statements per account.
        builder.HasIndex(l => new { l.AccountId, l.EntryId });

        builder.HasOne(l => l.Account).WithMany().HasForeignKey(l => l.AccountId).OnDelete(DeleteBehavior.Restrict);
    }
}
